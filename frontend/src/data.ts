export function createDemoEvaluation(
  conversation: Conversation,
  checklist: Checklist,
  seed = 0,
): Evaluation {
  const snapshot: Checklist = JSON.parse(JSON.stringify(checklist));
  const operators = conversation.transcript.flatMap((m, i) =>
    m.speaker === "operator" ? [i] : [],
  );
  const last = operators[operators.length - 1];
  const isRU = conversation.language === "RU";
  const indices: Record<string, number> = isRU
    ? {
        greeting: 1,
        need: 1,
        identity: 3,
        consultation: 5,
        empathy: 3,
        management: 7,
        closing: 11,
        gross: 3,
      }
    : {
        greeting: 1,
        need: 1,
        identity: 3,
        consultation: 3,
        empathy: 1,
        management: 3,
        closing: last,
        gross: 3,
      };
  const results = snapshot.criteria.map((criterion) => {
    let value: number | null = criterion.type === "flag" ? 0 : criterion.max;
    let explanation =
      "Демонстрационная оценка. Проверьте выбранный фрагмент в контексте разговора.";
    if (criterion.type === "scale")
      value =
        criterion.steps[
          Math.max(
            0,
            criterion.steps.length -
              1 -
              (seed % 3 === 1 ? 1 : seed % 3 === 2 ? 2 : 0),
          )
        ];
    if (criterion.id === "greeting")
      explanation =
        "Оператор поприветствовал клиента на его языке и представился в первом ответе.";
    if (criterion.id === "need")
      explanation =
        "Оператор уточнил недостающую деталь перед ответом на запрос.";
    if (criterion.id === "identity") {
      value = isRU ? 0 : criterion.allowNA ? null : 0;
      explanation = isRU
        ? "До сообщения о найденной заявке проверка личности в переписке не подтверждена. Проверен участок от приветствия до раскрытия статуса обращения."
        : "Запрос касался общей инструкции по получению документа; защищённое действие и раскрытие данных не требовались.";
    }
    if (criterion.id === "consultation") {
      value = isRU
        ? criterion.steps.includes(10)
          ? 10
          : criterion.steps[Math.floor(criterion.steps.length / 2)]
        : criterion.max;
      explanation = isRU
        ? "Следующий шаг объяснён, но существенный вопрос о сроке ответа остался открытым. В демонстрации выбрана ступень «Часть запроса закрыта»."
        : "Оператор объяснил, где найти документ, и ответил на уточняющий вопрос.";
    }
    if (criterion.id === "empathy")
      explanation = isRU
        ? "Оператор отреагировал на неудобство клиента и сохранял вежливый тон."
        : "Оператор вежливо отвечает и предлагает помощь по запросу.";
    if (criterion.id === "management")
      explanation =
        "Ответы последовательны и понятны. Оценка ступени показана как демонстрационный пример.";
    if (criterion.id === "closing")
      explanation =
        "В конце разговора оператор поблагодарил клиента и попрощался.";
    if (criterion.type === "flag")
      explanation =
        "В демонстрационном разговоре не отмечены оскорбления, услуги в обход компании или раскрытие конфиденциальной информации. Флаг учитывается отдельно от баллов.";
    if (!conversation.seeded)
      explanation =
        "Демонстрационная оценка: показана первая реплика оператора для ручной проверки. Автоматический смысловой анализ ещё не подключён.";
    if (!operators.length) {
      value = criterion.allowNA ? null : 0;
      explanation =
        "Реплики оператора отсутствуют. Это демонстрационный результат, требующий ручной проверки.";
    }
    const index =
      conversation.seeded && indices[criterion.id] !== undefined
        ? indices[criterion.id]
        : operators[0];
    return {
      criterionId: criterion.id,
      value,
      explanation,
      evidence:
        index !== undefined && conversation.transcript[index] ? [index] : [],
    };
  });
  return {
    id: `eval-${conversation.id}-${Date.now()}-${seed}`,
    checklist: snapshot,
    results,
    createdAt: new Date().toISOString(),
  };
}
