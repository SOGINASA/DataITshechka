export const initialConversations: Conversation[] = Array.from(
  { length: 18 },
  (_, i) => {
    const language: Language = i % 5 === 2 ? "KZ" : i % 5 === 4 ? "EN" : "RU";
    const channel =
      i === 0 || i === 7 || i === 13 ? "voice call" : "agent chat";
    const transcript: Message[] = JSON.parse(
      JSON.stringify(language === "KZ" ? kz : language === "EN" ? en : ru),
    );
    const day = 7 - Math.floor(i / 3);
    const date = `2026-11-${String(day).padStart(2, "0")}T${String(11 - (i % 3)).padStart(2, "0")}:24:00+05:00`;
    if (channel === "voice call")
      transcript.forEach((m) => {
        const [minutes, seconds] = m.timestamp.split(":").map(Number);
        const d = new Date(date);
        d.setSeconds(d.getSeconds() + minutes * 60 + seconds);
        m.timestamp = d.toISOString();
      });
    const operator =
      language === "KZ"
        ? "Айдана Серик"
        : language === "EN"
          ? "Daniel Kim"
          : operators[i % operators.length];
    if (language === "RU")
      transcript[1].text = transcript[1].text.replace(
        "Алия",
        operator.split(" ")[0],
      );
    const conversation: Conversation = {
      seeded: true,
      id: `${channel === "voice call" ? "call" : "chat"}-${language.toLowerCase()}-${String(24 + i).padStart(3, "0")}`,
      title:
        language === "RU"
          ? [
              "Сроки вывода средств",
              "Статус банковского перевода",
              "Проверка заявки на вывод",
            ][i % 3]
          : language === "KZ"
            ? "Шот бойынша үзінді көшірме"
            : "Account statement for October",
      operator,
      channel,
      language,
      date,
      duration:
        language === "RU" ? "03:02" : language === "KZ" ? "01:50" : "02:08",
      transcript,
      audioUrl: null,
      evaluations: [],
    };
    if (i !== 4 && i !== 8 && i !== 15) {
      const evaluation = createDemoEvaluation(
        conversation,
        initialChecklist,
        i,
      );
      evaluation.id = `eval-seed-${i}`;
      evaluation.createdAt = date;
      conversation.evaluations = [evaluation];
    }
    return conversation;
  },
);
