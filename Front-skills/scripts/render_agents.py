#!/usr/bin/env python3
"""Render native Codex/Claude agents from one shared source. Read-only unless --write."""
import argparse
import json
import re
import sys
import tomllib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def load_roles(root):
    roles = json.loads((root/'agents/roles.json').read_text())
    names = set()
    for role in roles:
        name = role['name']
        if not re.fullmatch(r'frontend-[a-z0-9-]+', name) or name in names:
            raise ValueError(f'Invalid or duplicate role: {name}')
        names.add(name)
        if role['mode'] not in ('write', 'review', 'design'):
            raise ValueError(f'Invalid role mode: {name}')
        p = (root/'agents'/role['prompt']).resolve()
        if not p.is_relative_to((root/'agents/roles').resolve()) or not p.is_file():
            raise ValueError(f'Invalid role source: {name}')
        for skill in role['skills']:
            if not re.fullmatch(r'[a-z][a-z0-9-]+', skill) or not (root/'skills'/skill/'SKILL.md').is_file():
                raise ValueError(f'Missing skill: {skill}')
    return roles

def render(root):
    root = root.resolve()
    roles = load_roles(root)
    common = (root/'agents/common.md').read_text().strip()
    contract = root/'skills/frontend-team/references/agent-contract.md'
    if not contract.is_file():
        raise ValueError('Missing shared contract')
    result = {}
    for role in roles:
        sources = [str(root/'skills'/s/'SKILL.md') for s in role['skills']]
        body = common+'\n\nRequired skill entrypoints (read these current files):\n'
        body += '\n'.join('- '+p for p in sources)
        body += '\n\nShared contract (read before work):\n'+str(contract)
        body += '\n\n'+(root/'agents'/role['prompt']).read_text().strip()+'\n'
        # TOML multiline basic strings: escape quotes/backslashes; body is normalized text.
        escaped = body.replace('\\','\\\\').replace('"','\\"')
        native = '# Generated by scripts/render_agents.py; edit agents/ sources instead.\n'
        native += 'name = '+json.dumps(role['name'])+'\n'
        native += 'description = '+json.dumps(role['description'],ensure_ascii=False)+'\n'
        native += 'developer_instructions = """\n'+escaped+'"""\n'
        parsed = tomllib.loads(native)
        if parsed['developer_instructions'] != body:
            raise ValueError('TOML roundtrip changed prompt: '+role['name'])
        result['agents/codex/'+role['name']+'.toml'] = native
        denied = ['Agent'] if role['mode']=='write' else ['Write','Edit','NotebookEdit','Agent']
        native = '---\nname: '+json.dumps(role['name'])+'\ndescription: '+json.dumps(role['description'],ensure_ascii=False)+'\nmodel: inherit\nskills:\n'
        native += ''.join('  - '+s+'\n' for s in role['skills'])
        native += 'disallowedTools:\n'+''.join('  - '+s+'\n' for s in denied)
        native += '---\n\n'+body
        result['agents/claude/'+role['name']+'.md'] = native
    return result

def check(root):
    expected = render(root)
    errors = [rel for rel,text in expected.items() if not (root/rel).is_file() or (root/rel).read_text()!=text]
    actual = {p.relative_to(root).as_posix() for folder,ext in [('codex','toml'),('claude','md')]
              for p in (root/'agents'/folder).glob('*.'+ext)}
    errors += sorted(actual-set(expected))
    return errors

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write',action='store_true',help='Regenerate kit adapters with the current kit path')
    args=parser.parse_args()
    try:
        expected=render(ROOT)
        if args.write:
            for rel,content in expected.items():
                p=ROOT/rel
                p.parent.mkdir(parents=True,exist_ok=True)
                p.write_text(content)
        errors=check(ROOT)
        print(json.dumps({'status':'FAIL' if errors else 'PASS','native_files':len(expected),'kit_root':str(ROOT),'drift':errors},indent=2))
        return bool(errors)
    except (ValueError,OSError,KeyError) as exc:
        print(str(exc),file=sys.stderr)
        return 1
if __name__=='__main__':
    sys.exit(main())
